/**
 * 提取话题标签
 * @param {string} title   标题
 * @param {string} summary 摘要（不喂入超长 brief，避免泛词污染）
 * @returns {string[]} 2~4 个标签，具体实体在前、主题簇在后
 */
function extractTopicTags(title, summary) {
  const text = `${title || ""} ${summary || ""}`;
  const out = [];

  // 1) 具体实体标签（按顺序、去重，最多取 3 个）
  for (const { kw, tag } of SPECIFIC) {
    if (out.includes(tag)) continue;
    if (kw.some(k => text.includes(k))) out.push(tag);
    if (out.length >= 3) break;
  }

  // 2) 主题簇（取第一个命中的，避免重复）
  for (const { kw, tag } of THEME) {
    if (out.includes(tag)) break;
    if (kw.some(k => text.includes(k))) { out.push(tag); break; }
  }

  // 3) 兜底：实在没匹配到，给个通用标签
  if (out.length === 0) out.push("外贸");

  return out.slice(0, 4);
}

module.exports = { extractTopicTags, SPECIFIC, THEME };
